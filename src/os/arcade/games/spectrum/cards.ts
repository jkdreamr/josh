/** The cards to deal from: the everyday deck, plus After Dark when the table turned it on. */
export const deckFor = (afterDark: boolean): readonly Card[] => (afterDark ? [...CARDS, ...AFTER_DARK] : CARDS);

/** How many two-color stocks the cards are printed on. The CSS defines `.is-stock0` and up. */
export const STOCKS = 6;

/** The color stock a card is printed on: steady for a card, varied across the deck, like a real box of cards. */
export function stockOf(card: Card): number {
  let h = 7;
  for (const ch of card[0] + '|' + card[1]) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % STOCKS;
}
